static bool lang_english;

static const wchar_t *tr(const wchar_t *s)
{
	if(lang_english)
		for(size_t i = 0; i < sizeof(english) / sizeof(english[0]); i++)
			if(wcscmp(english[i][0], s) == 0)
				return english[i][1];
	return s;
}
